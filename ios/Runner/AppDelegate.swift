import Flutter
import UIKit
import DeviceCheck

@main
@objc class AppDelegate: FlutterAppDelegate, FlutterImplicitEngineDelegate {
  override func application(
    _ application: UIApplication,
    didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]?
  ) -> Bool {
    // Prevent screenshots and screen recording across all screens.
    NotificationCenter.default.addObserver(
      self,
      selector: #selector(windowDidBecomeKey(_:)),
      name: UIWindow.didBecomeKeyNotification,
      object: nil
    )
    return super.application(application, didFinishLaunchingWithOptions: launchOptions)
  }

  // MARK: - Screenshot protection

  private let securedWindows = NSHashTable<UIWindow>.weakObjects()

  @objc private func windowDidBecomeKey(_ notification: Notification) {
    guard let window = notification.object as? UIWindow,
          window.rootViewController is FlutterViewController,
          !securedWindows.contains(window) else { return }
    securedWindows.add(window)
    secure(window)
  }

  /// iOS has no FLAG_SECURE equivalent. Hosting the window's layer inside the
  /// secure container of a password UITextField makes the system render the
  /// app content blank in screenshots, screen recordings and mirroring.
  private func secure(_ window: UIWindow) {
    let secureField = UITextField()
    secureField.isSecureTextEntry = true
    secureField.isUserInteractionEnabled = false
    secureField.translatesAutoresizingMaskIntoConstraints = false
    window.addSubview(secureField)
    NSLayoutConstraint.activate([
      secureField.centerXAnchor.constraint(equalTo: window.centerXAnchor),
      secureField.centerYAnchor.constraint(equalTo: window.centerYAnchor),
    ])

    window.layer.superlayer?.addSublayer(secureField.layer)
    if #available(iOS 17.0, *) {
      secureField.layer.sublayers?.last?.addSublayer(window.layer)
    } else {
      secureField.layer.sublayers?.first?.addSublayer(window.layer)
    }
  }

  func didInitializeImplicitFlutterEngine(_ engineBridge: FlutterImplicitEngineBridge) {
    GeneratedPluginRegistrant.register(with: engineBridge.pluginRegistry)

    // ── App Attest / Integrity channel ─────────────────────────────────────
    let registrar = engineBridge.pluginRegistry.registrar(forPlugin: "IntegrityPlugin")
    let messenger = registrar?.messenger()
    guard let messenger = messenger else { return }

    let integrityChannel = FlutterMethodChannel(
      name: "com.enagarsewa.app/integrity",
      binaryMessenger: messenger
    )

    integrityChannel.setMethodCallHandler { [weak self] call, result in
      switch call.method {
      case "generateKey":
        self?.generateAttestKey(result: result)

      case "attestKey":
        guard let args = call.arguments as? [String: String],
              let keyId = args["keyId"],
              let clientDataHash = args["clientDataHash"] else {
          result(FlutterError(
            code: "INVALID_ARGS",
            message: "Missing keyId or clientDataHash",
            details: nil
          ))
          return
        }

        self?.attestKey(
          keyId: keyId,
          clientDataHash: clientDataHash,
          result: result
        )

      default:
        result(FlutterMethodNotImplemented)
      }
    }
  }

  // MARK: - App Attest

  /// Generates a new App Attest key in the Secure Enclave.
  /// Returns the key identifier.
  private func generateAttestKey(result: @escaping FlutterResult) {
    let service = DCAppAttestService.shared

    guard service.isSupported else {
      result(FlutterError(
        code: "NOT_SUPPORTED",
        message: "App Attest is not supported on this device (requires iOS 14+ on real hardware)",
        details: nil
      ))
      return
    }

    service.generateKey { keyId, error in
      if let error = error {
        result(self.flutterError(from: error, fallbackCode: "KEY_GEN_ERROR"))
      } else {
        result(keyId)
      }
    }
  }

  /// Maps DCError codes to stable Flutter error codes.
  private func flutterError(from error: Error, fallbackCode: String) -> FlutterError {
    var code = fallbackCode
    if let dcError = error as? DCError {
      switch dcError.code {
      case .invalidKey, .invalidInput:
        code = "INVALID_KEY"
      case .serverUnavailable:
        code = "SERVER_UNAVAILABLE"
      case .featureUnsupported:
        code = "NOT_SUPPORTED"
      default:
        break
      }
    }
    return FlutterError(code: code, message: error.localizedDescription, details: nil)
  }

  /// Attests the key generated by generateAttestKey().
  /// clientDataHash must be a Base64-encoded SHA-256 hash (32 bytes).
  private func attestKey(
    keyId: String,
    clientDataHash: String,
    result: @escaping FlutterResult
  ) {
    let service = DCAppAttestService.shared

    guard service.isSupported else {
      result(FlutterError(
        code: "NOT_SUPPORTED",
        message: "App Attest not supported",
        details: nil
      ))
      return
    }

    guard let hashData = Data(base64Encoded: clientDataHash),
          hashData.count == 32 else {
      result(FlutterError(
        code: "INVALID_HASH",
        message: "clientDataHash must be Base64-encoded SHA-256 (32 bytes)",
        details: nil
      ))
      return
    }

    service.attestKey(
      keyId,
      clientDataHash: hashData
    ) { attestation, error in

      if let error = error {
        result(self.flutterError(from: error, fallbackCode: "ATTEST_ERROR"))
      } else if let attestation = attestation {
        result(attestation.base64EncodedString())
      } else {
        result(FlutterError(
          code: "ATTEST_ERROR",
          message: "No attestation data returned",
          details: nil
        ))
      }
    }
  }
}
